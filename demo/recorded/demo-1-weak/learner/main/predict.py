_X = _DATA[:, :3]
_Y = _DATA[:, 3]

def _phi(c: float, p: float, s: float) -> np.ndarray:
    a = abs(p)
    return np.array([
        1.0, c, a, s, c * a, c * s, a * s,
        c * c, a * a, s * s, c * c * a, c * a * a, c * c * s, a * a * s, c * a * s,
    ], dtype=float)

_A = np.vstack([_phi(c, p, s) for c, p, s in _X])
_L2 = 0.03
_COEF = np.linalg.solve(_A.T @ _A + _L2 * np.eye(_A.shape[1]), _A.T @ _Y)

def _base_predict(c: float, p: float, s: float) -> float:
    poly = float(_phi(c, p, s) @ _COEF)
    pts = np.c_[_X[:, 0], np.abs(_X[:, 1]), _X[:, 2]]
    q = np.array([c, abs(p), s], dtype=float)
    scale = np.array([0.22, 0.22, 0.04], dtype=float)
    d = np.linalg.norm((pts - q) / scale, axis=1)
    k = min(10, len(d))
    idx = np.argsort(d)[:k]
    w = np.exp(-0.5 * d[idx] * d[idx])
    w = w / max(float(np.sum(w)), 1e-12)
    local = float(np.sum(w * _Y[idx]))
    return 0.55 * poly + 0.45 * local

def predict(knobs: dict, visible: dict) -> list[float]:
    c = float(knobs["cock"])
    p = float(knobs["power"])
    s = float(knobs["shift"])

    stop_x = float(visible.get("stop_post.posx", -0.04))
    striker_z = float(visible.get("striker.posz", 0.71))

    # Approximate geometry transfer for visible dimension shifts.
    dx = stop_x - (-0.04)
    dz = striker_z - 0.71
    c_eff = c - 4.5 * dx - 0.8 * dz
    y = _base_predict(c_eff, p, s) + 5.5 * dx - 0.6 * dz
    return [float(y)]

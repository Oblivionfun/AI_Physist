def _features(cock: float, power: float, shift: float) -> np.ndarray:
    c = float(cock)
    p = float(power)
    s = float(shift)
    return np.array(
        [
            1.0,
            c,
            p,
            s,
            c * c,
            p * p,
            s * s,
            c * p,
            c * s,
            p * s,
            c * c * c,
            p * p * p,
            s * s * s,
            c * c * p,
            c * p * p,
            c * c * s,
            c * s * s,
            p * p * s,
            p * s * s,
            c * p * s,
        ],
        dtype=float,
    )


def predict(knobs: dict, visible: dict) -> list[float]:
    c = float(knobs["cock"])
    p = float(knobs["power"])
    s = float(knobs["shift"])

    y = float(_features(c, p, s) @ W)

    # Small geometry correction for evaluation on modified visible dimensions.
    dx_post = float(visible.get("stop_post.posx", -0.04)) - (-0.04)
    dz_striker = float(visible.get("striker.posz", 0.71)) - 0.71
    y += 3.0 * dx_post + 1.2 * dz_striker + 6.0 * dx_post * dz_striker

    return [y]
